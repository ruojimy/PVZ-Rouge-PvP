"""Generate src/sim/match_globals.inc from the translator's global-name lists
(+ EXTRA names used by hand-written PvP code)."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
EXTRA = ["_pvp_native_tick", "_pvp_water_ice", "补帧", "_pvp_target_extras", "_pvp_rally_speed", "地刺阳光",
         "__native_landing", "__native_displacement", "__native_original_out", "__native_original_open_top",
         "event", "左走", "右走", "跳跃", "_dummy"]
names = set(EXTRA)
for f in (ROOT / "src/sim/gen").glob("*.globals.txt"):
    names |= {l.strip() for l in f.read_text(encoding="utf-8").splitlines() if l.strip()}
for f in (ROOT / "src/sim/pvp/hand").glob("*.cpp"):
    import re
    names |= set(re.findall(r"Gp?(?:->|\.)([^\W\d][\w]*)", f.read_text(encoding="utf-8")))
names -= {"global", "find_global", "has_global", "rng", "rng_p", "own_rng", "rng_randint", "rng_random", "rng_choice",
          "rng_uniform", "rng_shuffle", "pygame_attr", "extra_globals"}
skip = {"True", "False", "None"}
names = sorted(n for n in names if n not in skip and n.isidentifier())
lines = ["// Generated by tools/gen_match_globals.py", "#define MATCH_GLOBALS(X) \\"]
lines += ["    X(%s) \\" % n for n in names]
(ROOT / "src/sim/match_globals.inc").write_text("\n".join(lines) + "\n\n", encoding="utf-8")
print(len(names), "globals")

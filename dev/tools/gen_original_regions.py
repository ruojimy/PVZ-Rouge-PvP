"""Stage the original isolated combat C++ separately from live PvP-injected regions."""
import argparse,ast,dis,hashlib,json,marshal,re,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'tools'))
from pydec38 import Decompiler
import py2cpp as g
REFERENCE=Path(r'C:\Users\xiech\Downloads\PVZ-Rouge-v1.4.8\next-pvp71')
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--out',required=True);args=ap.parse_args()
    out=Path(args.out).resolve();out.mkdir(parents=True,exist_ok=False)
    source=REFERENCE/'reverse_engineered/raw/pvzrouge.pyc';raw=source.read_bytes();code=marshal.loads(raw)
    runtime=REFERENCE/'modkit/pvp/native_runtime.py';tree=ast.parse(runtime.read_text(encoding='utf-8'))
    ranges=next(ast.literal_eval(n.value) for n in tree.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='REGIONS' for t in n.targets))
    # Execute only the original code-construction function, never the combat
    # regions. It retains the shipped isolation jumps and split-routing fix.
    sys.dont_write_bytecode=True;sys.path.insert(0,str(REFERENCE/'modkit'))
    from pvp.native_physics import slice_original,_instruction
    from pvp.native_bytecode import instructions as source_instructions
    construction=next(n for n in tree.body if isinstance(n,ast.FunctionDef) and n.name=='original_regions')
    namespace=dict(REGIONS=ranges,_COMPILED={},slice_original=slice_original,_instruction=_instruction,source_instructions=source_instructions)
    exec(compile(ast.Module(body=[construction],type_ignores=[]),str(runtime),'exec'),namespace)
    actual_regions=namespace['original_regions'](code)
    instructions=list(dis.get_instructions(code));corrections=[]
    for offset in (116462,116898):
        jump=next(i for i in instructions if i.offset==offset)
        assert jump.opname=='JUMP_ABSOLUTE' and jump.argval<offset,jump
        head=next(i for i in instructions if i.offset>=jump.argval and i.opname!='EXTENDED_ARG')
        assert head.opname=='FOR_ITER',head
        corrections.append(dict(offset=offset,opname=jump.opname,target=jump.argval,loop_head=head.offset,loop_instruction=head.opname))
    known=set(re.findall(r'X\((\w+)\)',(ROOT/'src/sim/match_globals.inc').read_text(encoding='utf-8')))
    class RawTranslator(g.Translator):
        def name(self,name,context):
            if not context.is_local(name) and name not in known and name not in ('True','False','None'):
                self.globals_used.add(name);return 'G.global(%s)'%self.sv(name)
            return super().name(name,context)
    translator=RawTranslator();parts=[];regions=[]
    # Gated source-line PC mappings are not source mappings for the raw region.
    # Callee PC offsets from the original bytecode remain valid.
    g.CALL_SITE_LINES={}
    for name in ('zombies','plants','entities','plant_maintenance'):
        start,end=ranges[name];actual=actual_regions[name]
        text='\n'.join(Decompiler(actual,start,end).decompile_lines())+'\n'
        (out/(name+'.py')).write_text(text,encoding='utf-8')
        if name=='plant_maintenance':
            for correction in corrections:text=text.replace('# goto @'+str(correction['offset']),'continue')
        assert '# goto' not in text and '# ??' not in text and 'GOTO' not in text
        (out/(name+'.corrected.py')).write_text(text,encoding='utf-8')
        translator.region=name;body=translator.block(ast.parse(text).body,g.Ctx('region'),'    ')
        parts.append('void region_original_%s(Match& G) {\n%s\n}\n'%(name,'\n'.join(body)))
        regions.append(dict(name=name,start=start,end=end,raw_bytecode_sha256=hashlib.sha256(code.co_code[start:end]).hexdigest(),isolated_bytecode_sha256=hashlib.sha256(actual.co_code[start:end]).hexdigest(),ast_sha256=hashlib.sha256(ast.dump(ast.parse(text)).encode()).hexdigest()))
    assert not translator.problems,translator.problems
    cpp='// Generated by tools/gen_original_regions.py; original isolated combat, before PvP injection.\n#include "sim/pyrt.h"\nnamespace pvz {\n'+'\n'.join(parts)+'\n}\n'
    (out/'original_regions.cpp').write_text(cpp,encoding='utf-8')
    provenance=dict(source=str(source),sha256=hashlib.sha256(raw).hexdigest(),runtime_sha256=hashlib.sha256(runtime.read_bytes()).hexdigest(),region_constructor_ast_sha256=hashlib.sha256(ast.dump(construction).encode()).hexdigest(),regions=regions,corrections=corrections,dynamic_globals=sorted(translator.globals_used-known),translator_problems=translator.problems,cpp_sha256=hashlib.sha256(cpp.encode()).hexdigest(),role='original isolated NativeRuntime regions from unchanged original_regions constructor; NativeBattle explicitly selects existing PvP regions',frame_positions='callee offsets retained; gated line map omitted')
    (out/'provenance.json').write_text(json.dumps(provenance,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(dict(bytes=len(cpp),dynamic_globals=provenance['dynamic_globals'],problems=translator.problems),ensure_ascii=False))
if __name__=='__main__':main()

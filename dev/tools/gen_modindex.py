# Writes src/ui/gen/modules_index.cpp: importlib.import_module("pvp.<name>") (and the modkit.pvp.<name> path)
# for every translated module - the UI modules plus the simulation-side translated / shim modules.
# (Referencing each module_ns() here also keeps dynamically-imported modules - the AI brains - linked in.)
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
GEN = SRC / "ui" / "gen"


def with_ns(folder):
    """Translated module headers that actually declare module_ns() (hand shims without one are skipped)."""
    return {p.stem[3:]: p.relative_to(SRC).as_posix() for p in sorted(folder.glob("pm_*.h"))
            if "V module_ns()" in p.read_text(encoding="utf-8", errors="replace")}


# precedence: UI translation, then simulation translation, then simulation shims
table = {}
for folder in (GEN, SRC / "sim" / "pvp" / "gen", SRC / "sim" / "pvp" / "shim"):
    for name, header in with_ns(folder).items():
        table.setdefault(name, header)
mods = sorted(table)
lines = ["// Generated by tools/gen_modindex.py - do not edit by hand.", '#include "sim/pvp/pvprt.h"']
lines += ['#include "%s"' % table[m] for m in mods]
lines.append("namespace pvz { namespace py {")
lines.append("V import_pvp_module(const std::string& qualname) {")
lines.append('    std::string n = qualname;')
lines.append('    if (n.rfind("modkit.", 0) == 0) n = n.substr(7);')
lines.append('    if (n.rfind("pvp.", 0) == 0) n = n.substr(4);')
for m in mods:
    lines.append('    if (n == "%s") return pm_%s::module_ns();' % (m, m))
lines.append('    throw PyError("ModuleNotFoundError", "No module named " + qualname);')
lines.append("}")
lines.append("}}  // namespace pvz::py")
(GEN / "modules_index.cpp").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
print("modules_index:", len(mods))

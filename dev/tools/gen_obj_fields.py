"""Generate src/core/obj_fields.inc: the member keys of Obj (all unit/avatar dicts).

Keys come from extract/schema/keys.json plus EXTRA below (added while porting).
Keys that are not valid C++ identifiers stay dynamic (Obj::extras).
"""
import json, keyword
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
CPP_KW = set("""alignas alignof and and_eq asm auto bitand bitor bool break case catch char char8_t char16_t
char32_t class compl concept const consteval constexpr constinit const_cast continue co_await co_return
co_yield decltype default delete do double dynamic_cast else enum explicit export extern false float for
friend goto if inline int long mutable namespace new noexcept not not_eq nullptr operator or or_eq private
protected public register reinterpret_cast requires return short signed sizeof static static_assert
static_cast struct switch template this thread_local throw true try typedef typeid typename union unsigned
using virtual void volatile wchar_t while xor xor_eq""".split())
# Keys discovered while porting (keep sorted by origin)
EXTRA = [
]
k = json.loads((ROOT / "extract/schema/keys.json").read_text(encoding="utf-8"))
names = []
for coll in ("僵尸", "植物", "实体", "avatar"):
    for key in k[coll]:
        if key not in names:
            names.append(key)
for key in EXTRA:
    if key not in names:
        names.append(key)
good = [n for n in names if n.isidentifier() and n not in CPP_KW and not n.startswith("__pvz_sb_K")]
bad = [n for n in names if n not in good]
lines = ["// Generated by tools/gen_obj_fields.py - do not edit by hand.", "#define OBJ_FIELDS(X) \\"]
for n in good:
    lines.append("    X(%s) \\" % n)
lines.append("")
lines.append("// %d member keys; dynamic-only: %s" % (len(good), " ".join(bad)))
(ROOT / "src/core/obj_fields.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(good), "member keys;", len(bad), "dynamic:", bad)

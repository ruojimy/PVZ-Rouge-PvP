"""Compile original test stimulus windows to C++; no expected output is embedded.

The target tests execute original collision/attack windows against live NativeTargets
callbacks. Those calls are stimuli for the product, so replaying their Python side effects
would bypass the native callbacks. These fixtures execute the original bodies natively.
"""
import ast
import hashlib
import json
import marshal
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from pydec38 import decompile
from py2cpp import Translator, Ctx

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(r"C:\Users\xiech\Downloads\PVZ-Rouge-v1.4.8\next-pvp71\reverse_engineered\raw\pvzrouge.pyc")
WINDOWS = {"pea_collision": (101746, 103540), "chomper": (133022, 134236),
           "cattail": (130014, 130492), "spike_tracking": (103540, 103934)}
payload = SOURCE.read_bytes()
code = marshal.loads(payload)
translator = Translator()
pieces, manifest = [], {}
for name, (start, end) in WINDOWS.items():
    text, problems = decompile(code, start, end)
    if problems or "# ??" in text:
        raise RuntimeError((name, "Original window did not decompile completely", problems))
    target = ROOT/"extract/original/test-windows"/(name + ".py")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text + "\n", encoding="utf-8")
    translator.region = "test_window_" + name
    body = translator.block(ast.parse(text).body, Ctx("region"), "    ")
    pieces.append("void test_window_%s(Match& G) {\n%s\n}\n" % (name, "\n".join(body)))
    manifest[name] = dict(start=start, end=end, source_sha256=hashlib.sha256(target.read_bytes()).hexdigest())
if translator.problems:
    raise RuntimeError(("Incomplete C++ translation", translator.problems))
output = ROOT/"src/cpptests/native_window_fixtures.cpp"
output.write_text('// Generated by tools/gen_native_window_fixtures.py from original bytecode.\n'
                  '// Test stimuli only: real native callbacks calculate every effect.\n'
                  '#include "sim/pyrt.h"\nnamespace pvz {\n' + "\n".join(pieces) + '\n}\n', encoding="utf-8")
(ROOT/"extract/schema/native-window-fixtures.json").write_text(json.dumps(dict(
    pyc_sha256=hashlib.sha256(payload).hexdigest(), windows=manifest,
    output_sha256=hashlib.sha256(output.read_bytes()).hexdigest()), ensure_ascii=False, indent=2), encoding="utf-8")
print(json.dumps(dict(windows=len(WINDOWS), globals=len(translator.globals_used), problems=0)), flush=True)
